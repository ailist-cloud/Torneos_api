CREATE TABLE usuario (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL,
    email   VARCHAR(150) NOT NULL UNIQUE,
    rol     VARCHAR(20)  NOT NULL
            CHECK (rol IN ('ORGANIZADOR', 'REPRESENTANTE', 'PUBLICO'))
);

CREATE TABLE torneo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    deporte          VARCHAR(50)  NOT NULL,
    fecha_inicio     DATE         NOT NULL,
    fecha_fin        DATE         NOT NULL,
    estado           VARCHAR(20)  NOT NULL
                     CHECK (estado IN ('ABIERTO', 'CERRADO', 'EN_CURSO', 'FINALIZADO')),
    puntos_victoria  INTEGER      NOT NULL CHECK (puntos_victoria >= 0),
    puntos_empate    INTEGER      NOT NULL CHECK (puntos_empate >= 0),
    puntos_derrota   INTEGER      NOT NULL CHECK (puntos_derrota >= 0),
    organizador_id   BIGINT       NOT NULL REFERENCES usuario (id),
    CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE criterio_desempate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id  BIGINT      NOT NULL REFERENCES torneo (id) ON DELETE CASCADE,
    orden      INTEGER     NOT NULL CHECK (orden > 0),
    criterio   VARCHAR(30) NOT NULL
               CHECK (criterio IN ('DIFERENCIA_GOLES', 'GOLES_A_FAVOR', 'GOLES_EN_CONTRA', 'PARTIDOS_GANADOS')),
    UNIQUE (torneo_id, orden),
    UNIQUE (torneo_id, criterio)
);

CREATE TABLE equipo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(100) NOT NULL UNIQUE,
    ciudad            VARCHAR(100),
    representante_id  BIGINT REFERENCES usuario (id)
);

CREATE TABLE inscripcion (
    torneo_id          BIGINT NOT NULL REFERENCES torneo (id) ON DELETE CASCADE,
    equipo_id          BIGINT NOT NULL REFERENCES equipo (id),
    fecha_inscripcion  DATE   NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (torneo_id, equipo_id)
);

CREATE TABLE partido (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id            BIGINT      NOT NULL REFERENCES torneo (id) ON DELETE CASCADE,
    equipo_local_id      BIGINT      NOT NULL REFERENCES equipo (id),
    equipo_visitante_id  BIGINT      NOT NULL REFERENCES equipo (id),
    fecha_hora_inicio    TIMESTAMP   NOT NULL,
    duracion_min         INTEGER     NOT NULL CHECK (duracion_min > 0),
    estado               VARCHAR(20) NOT NULL
                         CHECK (estado IN ('PROGRAMADO', 'EN_JUEGO', 'FINALIZADO', 'CANCELADO')),
    goles_local          INTEGER CHECK (goles_local >= 0),       -- RN-03
    goles_visitante      INTEGER CHECK (goles_visitante >= 0),   -- RN-03
    CHECK (equipo_local_id <> equipo_visitante_id)
);
