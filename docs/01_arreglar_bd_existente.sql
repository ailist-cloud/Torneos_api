-- Ejecutar en pgAdmin (Query Tool) sobre torneos_db SI YA TIENES LAS TABLAS.
-- No borra datos. Se puede ejecutar varias veces sin problema.
--
-- Qué arregla:
--   1. Que los id se generen solos (si no, los POST fallan con
--      "null value in column id violates not-null constraint").
--   2. Que los estados/roles/criterios queden en MAYÚSCULAS, porque la API
--      ahora los lee como enum (ej: 'programado' -> 'PROGRAMADO').
-- =====================================================================

-- 1. id autoincremental en las 5 tablas que tienen id
DO $$
DECLARE
    tabla TEXT;
    siguiente BIGINT;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['usuario', 'torneo', 'equipo', 'partido', 'criterio_desempate'] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = tabla AND column_name = 'id'
                     AND is_identity = 'NO' AND column_default IS NULL) THEN
            EXECUTE format('SELECT COALESCE(MAX(id), 0) + 1 FROM %I', tabla) INTO siguiente;
            EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                           tabla, siguiente);
            RAISE NOTICE 'Tabla %: id ahora es autoincremental (empieza en %)', tabla, siguiente;
        ELSE
            RAISE NOTICE 'Tabla %: id ya era autoincremental', tabla;
        END IF;
    END LOOP;
END $$;

-- 2. Normalizar textos que la API lee como enum
UPDATE usuario            SET rol      = UPPER(TRIM(rol))      WHERE rol      <> UPPER(TRIM(rol));
UPDATE torneo             SET estado   = UPPER(TRIM(estado))   WHERE estado   <> UPPER(TRIM(estado));
UPDATE partido            SET estado   = UPPER(TRIM(estado))   WHERE estado   <> UPPER(TRIM(estado));
UPDATE criterio_desempate SET criterio = UPPER(TRIM(criterio)) WHERE criterio <> UPPER(TRIM(criterio));

-- 3. Revisión: estas consultas deben devolver 0 filas.
--    Si devuelven algo, ese registro tiene un valor que la API no reconoce: corrígelo a mano.
SELECT 'usuario' AS tabla, id, rol AS valor FROM usuario
 WHERE rol NOT IN ('ORGANIZADOR', 'REPRESENTANTE', 'PUBLICO')
UNION ALL
SELECT 'torneo', id, estado FROM torneo
 WHERE estado NOT IN ('ABIERTO', 'CERRADO', 'EN_CURSO', 'FINALIZADO')
UNION ALL
SELECT 'partido', id, estado FROM partido
 WHERE estado NOT IN ('PROGRAMADO', 'EN_JUEGO', 'FINALIZADO', 'CANCELADO')
UNION ALL
SELECT 'criterio_desempate', id, criterio FROM criterio_desempate
 WHERE criterio NOT IN ('DIFERENCIA_GOLES', 'GOLES_A_FAVOR', 'GOLES_EN_CONTRA', 'PARTIDOS_GANADOS');

-- 4. Torneos sin criterios de desempate (GET /api/torneos/{id}/tabla responde 422 por RN-05)
SELECT t.id, t.nombre AS torneo_sin_criterios
FROM torneo t
WHERE NOT EXISTS (SELECT 1 FROM criterio_desempate c WHERE c.torneo_id = t.id);
