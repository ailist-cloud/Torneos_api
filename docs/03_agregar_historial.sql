-- =====================================================================
-- 03_agregar_historial.sql
-- Agrega la tabla de TRAZABILIDAD (historial_cambio).
-- OBLIGATORIO si tu base ya existía: sin esta tabla la API no arranca
-- (ddl-auto=validate avisa "missing table [historial_cambio]").
-- Se puede ejecutar varias veces sin problema.
-- =====================================================================

CREATE TABLE IF NOT EXISTS historial_cambio (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad     VARCHAR(20)  NOT NULL CHECK (entidad IN ('PARTIDO', 'TORNEO')),
    entidad_id  BIGINT       NOT NULL,   -- sin FK a propósito: el historial se conserva aunque se borre el partido
    accion      VARCHAR(30)  NOT NULL,
    detalle     VARCHAR(255),
    usuario_id  BIGINT       REFERENCES usuario (id),
    fecha_hora  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_historial_entidad ON historial_cambio (entidad, entidad_id);
